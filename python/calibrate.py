"""Step 4: fit LVTAO on training participants, choose it on validation participants only.

Selection rule (fixed in config.py before any test run):
  minimise inferences/min  subject to
    validation time-weighted macro F1 >= best fixed-stride F1 - NONINFERIORITY_DELTA
    median detection delay <= MAX_MEDIAN_DELAY_S
Ties go to the higher F1. If nothing qualifies, the highest-F1 setting is kept and flagged.

Outputs (models/fold<k>/): lvtao_params.json, calibration_grid.csv
For config.FIRMWARE_FOLD also writes firmware/src/generated/controller_params.h
"""
import argparse
import itertools

import numpy as np
import pandas as pd

import config as C
import data as D
import metrics as M
from int8_model import CachedPredictor, Int8Model
from policies import FeatureCache, LvtaoParams, Policy, fit_feature_stats, run_policy


class ValSet:
    """Validation participants with prediction/feature caches shared by every grid point."""

    def __init__(self, pids, model):
        self.items = []
        for pid in pids:
            x, y, bounds = D.load(pid)
            self.items.append((x, y, bounds, CachedPredictor(model, x), FeatureCache(x)))

    def score(self, policy):
        ys, preds, delays, inferences, minutes = [], [], [], 0, 0.0
        for x, y, bounds, predict, features in self.items:
            trace = run_policy(policy, x, y, bounds, predict, features)
            y_pred = M.hold_predictions(trace, len(y), bounds)
            ys.append(y)
            preds.append(y_pred)
            delays.extend(M.detection_delays(y, y_pred, bounds)[0])
            c = M.cadence(trace, bounds)
            inferences += c["inferences"]
            minutes += c["stream_minutes"]
        m = M.classification(np.concatenate(ys), np.concatenate(preds))
        return {"macro_f1": m.get("macro_f1", 0.0),
                "delay_median_s": float(np.median(delays)) if delays else float("nan"),
                "inferences_per_min": inferences / minutes if minutes else 0.0}


def train_scores(params, pids):
    """Change-score distribution on training windows (consecutive windows within a segment)."""
    out = []
    for pid in pids:
        x, _, bounds = D.load(pid)
        feats = FeatureCache(x)
        for seg in bounds:
            prev = None
            for end in D.window_ends([seg], C.EVAL_STRIDE):
                nv, nt = params.normalized(*feats(end))
                if prev is not None:
                    out.append(params.score(nv, nt, prev))
                prev = (nv, nt)
    return np.array(out)


def search(base, val, train_pids, best_fixed_f1):
    qs = np.quantile(train_scores(base, train_pids), C.THRESHOLD_QUANTILES)
    rows = []
    for (t1, t2), h, dwell in itertools.product(itertools.combinations(qs, 2), C.HYSTERESIS_GRID, C.DWELL_GRID):
        params = LvtaoParams(**{**base.to_dict(), "t1": float(t1), "t2": float(t2), "hysteresis": h, "dwell": dwell})
        rows.append({**params.to_dict(), **val.score(Policy.lvtao(params))})
    grid = pd.DataFrame(rows)
    ok = (grid.macro_f1 >= best_fixed_f1 - C.NONINFERIORITY_DELTA) & (grid.delay_median_s <= C.MAX_MEDIAN_DELAY_S)
    grid["meets_criteria"] = ok
    if ok.any():
        chosen = grid[ok].sort_values(["inferences_per_min", "macro_f1"], ascending=[True, False]).iloc[0]
    else:
        print("  WARNING: no setting met the criteria on validation; keeping the highest-F1 one")
        chosen = grid.sort_values("macro_f1", ascending=False).iloc[0]
    fields = LvtaoParams.__dataclass_fields__
    params = LvtaoParams(**{k: chosen[k] for k in fields})
    params.dwell = int(params.dwell)
    return params, chosen, grid


def write_controller_header(params, fold_id):
    C.FIRMWARE_GEN_DIR.mkdir(parents=True, exist_ok=True)
    f = D.c_float
    (C.FIRMWARE_GEN_DIR / "controller_params.h").write_text(f"""// Generated by python/calibrate.py from fold {fold_id}. Do not edit by hand.
#pragma once

constexpr float kFeatureEps = {f(C.FEATURE_EPS)};
constexpr float kMuLogVar = {f(params.mu_log_var)};
constexpr float kSdLogVar = {f(params.sd_log_var)};
constexpr float kMuLogTd = {f(params.mu_log_td)};
constexpr float kSdLogTd = {f(params.sd_log_td)};
constexpr float kT1 = {f(params.t1)};
constexpr float kT2 = {f(params.t2)};
constexpr float kHysteresis = {f(params.hysteresis)};
constexpr int kDwell = {int(params.dwell)};
constexpr int kStrides[3] = {{{', '.join(str(s) for s in C.LVTAO_STRIDES)}}};
constexpr int kInitialLevel = {C.LVTAO_INITIAL_LEVEL};
""")


def calibrate_fold(fold):
    out = D.fold_dir(fold["fold"])
    model = Int8Model(fold["fold"])
    val = ValSet(fold["val"], model)

    fixed = {s: val.score(Policy.fixed(s)) for s in C.FIXED_STRIDES}
    best_stride = max(fixed, key=lambda s: fixed[s]["macro_f1"])
    best_f1 = fixed[best_stride]["macro_f1"]
    print(f"fold {fold['fold']}: best fixed stride on validation = {best_stride} (macro F1 {best_f1:.3f})")

    base = fit_feature_stats(fold["train"])
    params, chosen, grid = search(base, val, fold["train"], best_f1)
    rate = chosen["inferences_per_min"]
    # Budget-matched control: the fixed stride with LVTAO's validation inference rate.
    budget = int(np.clip(round(C.FS * 60 / rate), min(C.LVTAO_STRIDES), max(C.LVTAO_STRIDES)))
    result = {"best_fixed_stride": best_stride, "fixed_validation": {str(k): v for k, v in fixed.items()},
              "lvtao": params.to_dict(),
              "lvtao_validation": {k: float(chosen[k]) for k in ("macro_f1", "delay_median_s", "inferences_per_min")},
              "lvtao_met_criteria": bool(chosen["meets_criteria"]),
              "budget_matched_stride": budget,
              "budget_matched_validation": val.score(Policy.fixed(budget))}
    print(f"  lvtao: t1={params.t1:.3f} t2={params.t2:.3f} h={params.hysteresis} dwell={params.dwell} "
          f"-> F1 {chosen['macro_f1']:.3f}, {rate:.1f} inf/min | budget-matched stride {budget}: "
          f"F1 {result['budget_matched_validation']['macro_f1']:.3f}")

    grid.to_csv(out / "calibration_grid.csv", index=False)
    D.save_json(out / "lvtao_params.json", result)
    if fold["fold"] == C.FIRMWARE_FOLD:
        write_controller_header(params, fold["fold"])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fold", type=int, help="calibrate one fold (default: all)")
    args = ap.parse_args()
    for fold in D.load_folds():
        if args.fold is None or fold["fold"] == args.fold:
            calibrate_fold(fold)


if __name__ == "__main__":
    main()
