"""Step 3: full-integer post-training quantization + firmware headers.

Outputs (models/fold<k>/): model_int8.tflite, quant_info.json
For config.FIRMWARE_FOLD also writes firmware/src/generated/{model_data.h, norm.h, bench_data.h}.
"""
import argparse

import numpy as np
import tensorflow as tf
from sklearn.metrics import accuracy_score, f1_score

import config as C
import data as D
from int8_model import Int8Model


def convert(model, representative):
    converter = tf.lite.TFLiteConverter.from_keras_model(model)
    converter.optimizations = [tf.lite.Optimize.DEFAULT]
    converter.representative_dataset = lambda: ([w[None]] for w in representative)
    converter.target_spec.supported_ops = [tf.lite.OpsSet.TFLITE_BUILTINS_INT8]
    converter.inference_input_type = tf.int8
    converter.inference_output_type = tf.int8
    return converter.convert()


def scores(y, pred):
    return {"accuracy": float(accuracy_score(y, pred)),
            "macro_f1": float(f1_score(y, pred, average="macro", labels=np.unique(y), zero_division=0))}


def c_array(name, values, ctype, per_line=12):
    body = ",\n  ".join(", ".join(values[i:i + per_line]) for i in range(0, len(values), per_line))
    return f"{ctype} {name}[] = {{\n  {body}\n}};\n"


def write_firmware_headers(fold, tflite_bytes, model):
    gen = C.FIRMWARE_GEN_DIR
    gen.mkdir(parents=True, exist_ok=True)
    note = f"// Generated by python/quantize.py from fold {fold['fold']}. Do not edit by hand.\n#pragma once\n#include <cstdint>\n\n"

    (gen / "model_data.h").write_text(
        note
        + c_array("alignas(16) const unsigned char g_model_data", [f"0x{b:02x}" for b in tflite_bytes], "", 16).lstrip()
        + f"const unsigned int g_model_data_len = {len(tflite_bytes)};\n")

    (gen / "norm.h").write_text(
        note
        + c_array("static const float kNormMean", [D.c_float(v) for v in model.mean], "").lstrip()
        + c_array("static const float kNormStd", [D.c_float(v) for v in model.std], "").lstrip())

    # Bench windows: evenly spaced labelled windows from this fold's test participants,
    # with the label the Python INT8 interpreter predicts, for the parity check.
    x_te, _ = D.labelled_windows(fold["test"], C.TRAIN_STRIDE)
    idx = np.linspace(0, len(x_te) - 1, C.N_BENCH_WINDOWS).astype(int)
    windows = x_te[idx]
    expected = [model.predict(w) for w in windows]
    flat = [D.c_float(v) for v in windows.reshape(-1)]
    (gen / "bench_data.h").write_text(
        note
        + f"constexpr int kBenchWindows = {C.N_BENCH_WINDOWS};\n"
        + c_array("static const float g_bench_raw", flat, "").lstrip()
        + c_array("static const int8_t g_bench_expected", [str(v) for v in expected], "").lstrip())
    D.save_json(D.fold_dir(fold["fold"]) / "bench_expected.json", {"expected": expected})
    print(f"wrote firmware headers to {gen}")


def quantize_fold(fold):
    out = D.fold_dir(fold["fold"])
    model = tf.keras.models.load_model(out / "model.keras")
    norm = D.load_json(out / "norm.json")
    mean, std = np.array(norm["mean"], np.float32), np.array(norm["std"], np.float32)

    x_tr, _ = D.labelled_windows(fold["train"], C.TRAIN_STRIDE)
    rng = np.random.default_rng(C.SEED)
    pick = rng.choice(len(x_tr), size=min(C.N_REPRESENTATIVE, len(x_tr)), replace=False)
    tflite_bytes = convert(model, D.normalize(x_tr[pick], mean, std))
    (out / "model_int8.tflite").write_bytes(tflite_bytes)

    int8 = Int8Model(fold["fold"])
    # DELEGATE is the desktop interpreter's XNNPACK delegate, not part of the model.
    ops = sorted({op["op_name"] for op in int8.interp._get_ops_details()} - {"DELEGATE"})
    info = {"int8_model_bytes": len(tflite_bytes), "float_model_bytes": (out / "model.keras").stat().st_size,
            "input_scale": float(int8.scale), "input_zero_point": int8.zero_point, "ops": ops}
    for split in ("val", "test"):
        x, y = D.labelled_windows(fold[split], C.TRAIN_STRIDE)
        float_pred = np.argmax(model.predict(D.normalize(x, mean, std), verbose=0), axis=1)
        int8_pred = np.array([int8.predict(w) for w in x])
        info[f"{split}_float"] = scores(y, float_pred)
        info[f"{split}_int8"] = scores(y, int8_pred)
        info[f"{split}_float_int8_agreement"] = float(np.mean(float_pred == int8_pred))
    D.save_json(out / "quant_info.json", info)
    print(f"fold {fold['fold']}: INT8 {len(tflite_bytes)} B, ops {ops}")
    print(f"  test macro F1 float {info['test_float']['macro_f1']:.3f} -> INT8 {info['test_int8']['macro_f1']:.3f}")

    if fold["fold"] == C.FIRMWARE_FOLD:
        write_firmware_headers(fold, tflite_bytes, int8)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--fold", type=int, help="quantize one fold (default: all)")
    args = ap.parse_args()
    for fold in D.load_folds():
        if args.fold is None or fold["fold"] == args.fold:
            quantize_fold(fold)


if __name__ == "__main__":
    main()
